# Рассчитать средний возраст n человек, n вводится с клавиатуры

n = int(input("Введите количество человек: "))

total = 0
for i in range(n):
    age = int(input(f"Введите возраст человека {i + 1}: "))
    total += age

average = total / n
print(f"Средний возраст: {int(average)}")

# На входе строка цветового кода (например "a0351f"),
# определить цвет ближе к красному, синему или зеленому.
# Вывести что цвет серый, если все значения равны, но цвет не черный и не белый.
# Вывести "черный" или "белый" если код 000000 или ffffff соответственно

code = input("Введите цветовой код (например a0351f): ").strip().lstrip("#").lower()

r = int(code[0:2], 16)
g = int(code[2:4], 16)
b = int(code[4:6], 16)

if code == "000000":
    print("черный")
elif code == "ffffff":
    print("белый")
elif r == g == b:
    print("серый")
else:
    m = max(r, g, b)
    if m == r:
        print("ближе к красному")
    elif m == g:
        print("ближе к зеленому")
    else:
        print("ближе к синему")